// src/tools/githubActions.js
import { Octokit } from '@octokit/rest';
import { execSync } from 'child_process';
import path from 'path';
import fs from 'fs';
import dotenv from 'dotenv';

// Load environment tokens
dotenv.config();

const octokit = new Octokit({ auth: process.env.GITHUB_TOKEN });

/**
 * Tool: Dynamically creates a brand new repository on your GitHub account via API.
 * This runs deterministically via code before the coding agent boots up.
 */
export async function createGitHubRepository({ repoName, description }) {
  try {
    console.log(`[GitHub API]: Requesting creation of public repository: "${repoName}"...`);
    
    const response = await octokit.repos.createForAuthenticatedUser({
      name: repoName,
      description: description || "Automated website generated by DevPipeline-Agent.",
      private: false,      // Must be public to use free GitHub Pages hosting
      auto_init: true      // Creates an initial main branch commit so we can clone it instantly
    });

    return {
      success: true,
      cloneUrl: response.data.clone_url,
      repoName: response.data.name,
      result: `Successfully provisioned GitHub repository: ${response.data.html_url}`
    };
  } catch (error) {
    return { error: `GitHub API Provisioning failed: ${error.message}` };
  }
}

/**
 * Tool: Clones the newly created GitHub repository into your isolated local workspace directory.
 */
export function cloneRepository({ repoUrl, repoName }) {
  try {
    // Establish the absolute path inside the ignored workspace/ folder
    const targetWorkspace = path.resolve(`./workspace/${repoName}`);

    // If an old sandbox folder exists from a previous run, clear it out safely
    if (fs.existsSync(targetWorkspace)) {
      fs.rmSync(targetWorkspace, { recursive: true, force: true });
    }
    
    // Create the root workspace directory if it's missing
    fs.mkdirSync(path.dirname(targetWorkspace), { recursive: true });

    console.log(`📥 [Git CLI]: Cloning remote repo down to: ${targetWorkspace}`);
    
    // Run native git clone shell command
    execSync(`git clone ${repoUrl} "${targetWorkspace}"`, { stdio: 'inherit' });

    return { 
      success: true, 
      workspacePath: targetWorkspace, 
      result: `Successfully cloned repository to isolated environment.` 
    };
  } catch (error) {
    return { error: `Local Git clone operation failed: ${error.message}` };
  }
}

/**
 * Tool: Executed by the Coding Agent to commit and push changes back to GitHub.
 */
export function pushToGitHub({ workspacePath, repoUrl }) {
  try {
    const targetDir = path.resolve(workspacePath);
    
    if (!fs.existsSync(targetDir)) {
      return { error: `Target workspace directory does not exist: ${workspacePath}` };
    }

    console.log(`📤 [Git CLI]: Committing compilation assets and executing remote push...`);

    // Run standard Git sequence inside the target directory coordinates
    execSync('git add .', { cwd: targetDir });
    execSync('git commit -m "Feat: Compilation assets generated by Autonomous Coding Agent"', { cwd: targetDir });
    execSync('git branch -M main', { cwd: targetDir });
    
    // Force push overrides the initial auto_init template file
    execSync('git push -u origin main --force', { cwd: targetDir });

    return { result: `Successfully pushed assets to remote repository main branch.` };
  } catch (error) {
    return { error: `Git push automation failed: ${error.message}` };
  }
}
